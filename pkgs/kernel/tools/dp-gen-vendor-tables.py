"""Generate C init tables for the combo PHY's DP side from a vendor capture.

The vendor stack computes its DP PLL/serdes values at runtime (VCO calibration,
SSC, lock thresholds), so no upstream table matches them. Its *live* register
state is the ground truth for the one mode this port uses (2560x1600@60 over
HBR2). This tool walks the offsets the mainline v6_n4 DP tables write, takes
the value the vendor left in each register, and emits drop-in
qmp_phy_init_tbl arrays.

Usage: dp-gen-vendor-tables.py CAPTURE... DRIVER.c
"""
import glob
import os
import re
import sys

BASES = {"dp_serdes": 0x88ea000, "dp_txa": 0x88ea200, "dp_txb": 0x88ea600}

TABLES = ["qmp_v6_n4_dp_serdes_tbl", "qmp_v6_n4_dp_serdes_tbl_hbr2",
          "qmp_v6_n4_dp_tx_tbl", "qmp_v6_dp_serdes_tbl", "qmp_v6_dp_tx_tbl"]


def load_capture(paths):
    regs = {}
    for p in paths:
        with open(p, errors="replace") as fh:
            for line in fh:
                if line.startswith("#"):
                    continue
                f = line.split()
                if len(f) == 2:
                    try:
                        regs[int(f[0], 16)] = int(f[1], 16)
                    except ValueError:
                        pass
    return regs


def main(captures, driver):
    regs = load_capture(captures)
    src = open(driver).read()
    for h in sorted(glob.glob(os.path.join(os.path.dirname(driver), "phy-qcom-qmp-*.h"))):
        src += open(h).read()

    defines = {}
    for m in re.finditer(r"^#define\s+((?:QSERDES_|QPHY_)\w+)\s+(0x[0-9a-fA-F]+)\s*$", src, re.M):
        defines.setdefault(m.group(1), int(m.group(2), 16))

    seen = set()
    print("/* generated by dp-gen-vendor-tables.py from the vendor live capture */")
    print("/* vendor: HBR2 4-lane, 2560x1600@60, widebus; values are live registers */")
    for tname in TABLES:
        tm = re.search(r"static const struct qmp_phy_init_tbl\s+%s\[\]\s*=\s*\{(.*?)\n\};"
                       % tname, src, re.S)
        if not tm:
            continue
        rows = re.findall(r"QMP_PHY_INIT_CFG\((\w+)\s*,\s*(0x[0-9a-fA-F]+)\)", tm.group(1))
        out, missing = [], []
        for macro, val in rows:
            off = defines.get(macro)
            if off is None:
                missing.append(macro)
                continue
            if "_DP_TX" in macro:
                bases = [("dp_txa", BASES["dp_txa"]), ("dp_txb", BASES["dp_txb"])]
            elif tname.endswith("tx_tbl"):
                bases = [("dp_txa", BASES["dp_txa"]), ("dp_txb", BASES["dp_txb"])]
            else:
                bases = [("dp_serdes", BASES["dp_serdes"])]
            for bname, base in bases:
                live = regs.get(base + off)
                if live is None:
                    missing.append("%s@%s+%#x" % (macro, bname, off))
                    continue
                key = (tname, bname, off)
                if key in seen:
                    continue
                seen.add(key)
                out.append((macro, bname, off, live))
        if not out and not missing:
            continue
        print("\n/* %s: %d registers */" % (tname, len(out)))
        print("static const struct qmp_phy_init_tbl liuqin_%s_from_vendor[] = {" % tname)
        for macro, bname, off, live in out:
            print("\tQMP_PHY_INIT_CFG(%s, 0x%08x),\t/* %s + %#x */"
                  % (macro, live, bname, off))
        print("};")
        if missing:
            print("/* not found in capture: %s */" % ", ".join(missing[:8]), file=sys.stderr)


if __name__ == "__main__":
    argv = sys.argv[1:]
    if len(argv) < 2:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    main(argv[:-1], argv[-1])
